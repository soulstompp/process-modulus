enum Narrowing {
    /// A single value has no width to tighten.
    NotApplicable,
    /// A generator knows which setting made the spread, so it can always fill this field: a bound
    /// that came from an instrument that did not record something narrows when the instrument is
    /// changed, and never by running again.
    Instrument(&'static str),
}

impl Narrowing {
    fn for_bound(b: Bounded, instrument: Instrument) -> Narrowing {
        match (b, instrument) {
            (Bounded::Range { low, high }, _) if (high - low).abs() < 1e-9 => {
                Narrowing::NotApplicable
            }
            (_, Instrument::StockAndFlow) => Narrowing::Instrument(
                "a refusal is logged with the quantity it turned away, rather than a reason \
                 alone",
            ),
            (_, Instrument::Whole) => Narrowing::NotApplicable,
        }
    }

    fn xml(&self, pad: usize) -> String {
        let p = " ".repeat(pad);
        match self {
            Narrowing::NotApplicable => format!(
                "{p}<pm:narrowsWhen><pm:absent><pm:reason>notApplicable</pm:reason>\
                 <pm:note>there is no range here to tighten</pm:note></pm:absent>\
                 </pm:narrowsWhen>\n"
            ),
            Narrowing::Instrument(condition) => format!(
                "{p}<pm:narrowsWhen>\n{p}  <pm:narrowing>\n{p}    \
                 <pm:condition>{condition}</pm:condition>\n{p}    \
                 <pm:kind>instrument</pm:kind>\n{p}  </pm:narrowing>\n{p}</pm:narrowsWhen>\n"
            ),
        }
    }
}

/// Who owns the edge of a claim.
///
/// There is no `none` variant, on purpose. `none` says the bound is where the measurements fell,
/// which describes a spread a single-value claim does not have, and `bound_fell_with_no_range`
/// rejects it there. The true answer for an exact observation is `notApplicable`. Without the
/// variant, the generator cannot make that mistake.
enum BoundOrigin<'a> {
    Intrinsic,
    Policy,
    NotApplicable(&'a str),
    /// The identity that names the author, and a note.
    Derivation(&'a str, &'a str),
}

impl BoundOrigin<'_> {
    fn xml(&self, pad: usize) -> String {
        let p = " ".repeat(pad);
        let absent = |reason: &str, note: &str| {
            format!(
                "{p}<pm:boundOrigin><pm:absent><pm:reason>{reason}</pm:reason>\
                 <pm:note>{note}</pm:note></pm:absent></pm:boundOrigin>\n"
            )
        };
        match self {
            BoundOrigin::Intrinsic => {
                format!("{p}<pm:boundOrigin><pm:origin>intrinsic</pm:origin></pm:boundOrigin>\n")
            }
            BoundOrigin::Policy => {
                format!("{p}<pm:boundOrigin><pm:origin>policy</pm:origin></pm:boundOrigin>\n")
            }
            BoundOrigin::NotApplicable(note) => absent("notApplicable", note),
            BoundOrigin::Derivation(identity, note) => format!(
                "{p}<pm:boundOrigin><pm:derivation><pm:identity>{identity}</pm:identity>\
                 <pm:note>{note}</pm:note></pm:derivation></pm:boundOrigin>\n"
            ),
        }
    }
}

/// One `pm:StatedClaim`, or the typed absence where the instrument had nothing.
fn claim(
    b: Bounded,
    narrows: Narrowing,
    origin: BoundOrigin<'_>,
    as_of: &str,
    pad: usize,
    absent_note: &str,
) -> String {
    let p = " ".repeat(pad);
    let (low, high) = match b {
        Bounded::Range { low, high } => (low, high),
        Bounded::Unmeasured => {
            return format!(
                "{p}<pm:absent>\n{p}  <pm:reason>unmeasured</pm:reason>\n{p}  \
                 <pm:note>{absent_note}</pm:note>\n{p}</pm:absent>\n"
            );
        }
    };
    let ml = (low + high) / 2.0;
    let mut x = String::new();
    x.push_str(&format!("{p}<pm:claim>\n"));
    x.push_str(&format!(
        "{p}  <pm:low>{low:.4}</pm:low><pm:mostLikely>{ml:.4}</pm:mostLikely>\
         <pm:high>{high:.4}</pm:high>\n"
    ));
    x.push_str(&format!("{p}  <pm:unit>{UNIT}</pm:unit>\n"));
    x.push_str(&format!(
        "{p}  <pm:denominator><pm:period>{PERIOD}</pm:period></pm:denominator>\n"
    ));
    x.push_str(&narrows.xml(pad + 2));
    x.push_str(&origin.xml(pad + 2));
    x.push_str(&format!(
        "{p}  <pm:provenance><pm:party>bench</pm:party>\n{p}    \
         <pm:standing><pm:term><pm:taxonomy>urn:example:assertion-standing:2026</pm:taxonomy>\
         <pm:value>generated</pm:value></pm:term></pm:standing>\n{p}  </pm:provenance>\n"
    ));
    x.push_str(&format!("{p}  <pm:asOf>{as_of}</pm:asOf>\n"));
    x.push_str(&format!("{p}</pm:claim>\n"));
    x
}

/// A bench knows its patience by construction, because it is a parameter of the run.
fn patience(s: &Settings, instrument: Instrument, as_of: &str) -> String {
    if instrument == Instrument::StockAndFlow {
        // A resource that waits for ever has no patience to record, so this is not a
        // measurement anybody omitted but a notion the instrument lacks.
        return "          <pm:absent>\n            <pm:reason>unmeasured</pm:reason>\n            \
<pm:note>nothing in a stock-and-flow log gives a queued demand a \
                lifetime, so how long one survives being unanswered is not recorded</pm:note>\n          \
</pm:absent>\n"
            .to_string();
    }
    // Zero patience is a claim of zero, not an absence. `Demand/patience` is a `StatedClaim`, so
    // its absence is a `ClaimAbsence`, and `ClaimAbsenceReason` has no `none`. That is right:
    // somebody measured how long this demand survives being held and the answer was nothing,
    // which is a measurement rather than a missing column.
    //
    // A patience is a span of time and not the layer's unit, which is what separates it from
    // `timeSlack`. It bounds no shares, so `slack_unit_mismatch` does not reach it.
    let secs = s.patience.as_secs_f64();
    format!(
        "          <pm:claim>\n            <pm:low>{secs:.1}</pm:low>\
         <pm:mostLikely>{secs:.1}</pm:mostLikely><pm:high>{secs:.1}</pm:high>\n            \
<pm:unit>seconds</pm:unit>\n            \
<pm:denominator><pm:absent><pm:reason>notApplicable</pm:reason>\
         </pm:absent></pm:denominator>\n            \
<pm:narrowsWhen><pm:absent><pm:reason>notApplicable</pm:reason>\
         <pm:note>there is no range here to tighten</pm:note></pm:absent></pm:narrowsWhen>\n            \
<pm:boundOrigin><pm:origin>policy</pm:origin></pm:boundOrigin>\n            \
<pm:asOf>{as_of}</pm:asOf>\n          </pm:claim>\n"
    )
}

/// The time buffer, in the layer's unit rather than in seconds.
///
/// The patience in seconds is multiplied by the demand rate to give a quantity in the layer's
/// unit. Once done, that step cannot be seen, so the note says it. `slack_unit_mismatch` requires
/// a slack in the unit of the shares it bounds, and a slack that skips the multiplication and
/// keeps the right unit is caught by nothing.
fn time_slack(run: &Run, r: &Reading, instrument: Instrument, as_of: &str) -> String {
    let s = &run.settings;
    if instrument == Instrument::StockAndFlow {
        return "        <pm:absent>\n          <pm:reason>unmeasured</pm:reason>\n          \
<pm:note>no wait is recorded against a demand, because no demand is \
                recorded until it succeeds</pm:note>\n        </pm:absent>\n"
            .to_string();
    }
    let Some(demand) = mode(r.demand) else {
        return "        <pm:absent>\n          <pm:reason>unmeasured</pm:reason>\n          \
<pm:note>the rate the wait would be multiplied by is not \
                measured</pm:note>\n        </pm:absent>\n"
            .to_string();
    };
    let rate = demand / run.window.as_secs_f64();
    let quantity = s.patience.as_secs_f64() * rate;
    let mut x = String::new();
    x.push_str("        <pm:claim>\n");
    x.push_str(&format!(
        "          <pm:low>{quantity:.4}</pm:low><pm:mostLikely>{quantity:.4}</pm:mostLikely>\
         <pm:high>{quantity:.4}</pm:high>\n"
    ));
    x.push_str(&format!("          <pm:unit>{UNIT}</pm:unit>\n"));
    x.push_str(&format!(
        "          <pm:denominator><pm:period>{PERIOD}</pm:period></pm:denominator>\n"
    ));
    x.push_str(&Narrowing::NotApplicable.xml(10));
    x.push_str("          <pm:boundOrigin><pm:origin>policy</pm:origin></pm:boundOrigin>\n");
    x.push_str(&format!(
        "          <pm:provenance><pm:party>bench</pm:party>\n            \
         <pm:standing><pm:term><pm:taxonomy>urn:example:assertion-standing:2026</pm:taxonomy>\
         <pm:value>generated</pm:value></pm:term></pm:standing>\n            \
         <pm:note>a patience of {p:.0} seconds at a demand rate of {rate:.4} {UNIT} per second \
         is {quantity:.2} {UNIT}. The multiplication is the bridge from the duration that was \
         measured to the quantity the field takes</pm:note>\n          </pm:provenance>\n",
        p = s.patience.as_secs_f64()
    ));
    x.push_str(&format!("          <pm:asOf>{as_of}</pm:asOf>\n        </pm:claim>\n"));
    x
}

/// The quantum, and the part of the period the line is live for.
fn divisibility(run: &Run, as_of: &str) -> String {
    let s = &run.settings;
    let mut x = String::new();
    x.push_str("          <pm:divisibility>\n            <pm:divisibility>\n");
    x.push_str("              <pm:lumpy>\n                <pm:size>\n");
    // The quantum is in the unit of the nameplate it divides, and this nameplate is a rate, so
    // the demand and the nameplate divided by it are counts of lots.
    x.push_str(&indent(
        &claim(
            Bounded::point(s.lot),
            Narrowing::NotApplicable,
            BoundOrigin::Derivation(
                "quantumOrigin",
                "`LumpyQuantum/origin` says who sets the size of one unit, in this same element",
            ),
            as_of,
            0,
            "",
        ),
        18,
    ));
    x.push_str("                </pm:size>\n");
    x.push_str("                <pm:origin>intrinsic</pm:origin>\n              </pm:lumpy>\n");
    // The time the line is live, not the gap. The line runs the whole shift without stopping, so
    // it is live for all of it and the window is the period.
    let hours = run.window.as_secs_f64() / 3600.0;
    x.push_str(&format!(
        "              <pm:window>\n                <pm:quantum>\n                  \
         <pm:size>\n                    <pm:claim>\n                      \
         <pm:low>{hours:.1}</pm:low><pm:mostLikely>{hours:.1}</pm:mostLikely>\
         <pm:high>{hours:.1}</pm:high>\n                      \
         <pm:unit>hours</pm:unit>\n                      \
         <pm:denominator><pm:period>{PERIOD}</pm:period></pm:denominator>\n                      \
         <pm:narrowsWhen><pm:absent><pm:reason>notApplicable</pm:reason>\
         <pm:note>there is no range here to tighten</pm:note></pm:absent></pm:narrowsWhen>\n                      \
<pm:boundOrigin><pm:origin>intrinsic</pm:origin>\
         </pm:boundOrigin>\n                      <pm:asOf>{as_of}</pm:asOf>\n                    \
         </pm:claim>\n                  </pm:size>\n                  \
         <pm:origin>intrinsic</pm:origin>\n                </pm:quantum>\n              \
         </pm:window>\n"
    ));
    x.push_str("            </pm:divisibility>\n          </pm:divisibility>\n");
    x
}

fn indent(block: &str, pad: usize) -> String {
    let p = " ".repeat(pad);
    block
        .lines()
        .map(|l| if l.is_empty() { l.to_string() } else { format!("{p}{l}") })
        .collect::<Vec<_>>()
        .join("\n")
        + "\n"
}
